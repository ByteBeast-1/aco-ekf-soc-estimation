function C = bms_nasa_calibrate(train_cell, train_idx)
%BMS_NASA_CALIBRATE Fit the NASA-cell OCV curve on ONE real cycle and write lib/bms_nasa_cal_data.m.
%   With the nominal RC network fixed, OCV_eff(SOC) = V + R0*I + V1 + V2 (RC states are simulated from
%   the measured current), then a polynomial in SOC is fitted. Calibrating on one cell (default B0006)
%   and evaluating on others (B0005, B0007) keeps the real-data results out-of-sample.
    if nargin < 1,  train_cell = 'B0006';  end
    if nargin < 2,  train_idx  = 1;        end

    D = bms_nasa_load(train_cell, train_idx);
    C.R0 = 0.060;  C.R1 = 0.030;  C.R2 = 0.020;      % nominal 18650 values
    C.C1 = 1500;   C.C2 = 10000;  C.Qn = 7200;       % 2.0 Ah nominal capacity [As]

    a1 = exp(-1 / (C.R1 * C.C1));  b1 = C.R1 * (1 - a1);
    a2 = exp(-1 / (C.R2 * C.C2));  b2 = C.R2 * (1 - a2);
    v1 = 0;  v2 = 0;  n = numel(D.t);  ocv_meas = zeros(n, 1);
    for k = 1:n
        v1 = a1 * v1 + b1 * D.I(k);
        v2 = a2 * v2 + b2 * D.I(k);
        ocv_meas(k) = D.V(k) + C.R0 * D.I(k) + v1 + v2;
    end

    deg = 8;
    [p, ~, mu] = polyfit(D.soc_ref, ocv_meas, deg);    % centred for conditioning
    s  = linspace(0, 1, 201)';
    v  = polyval(p, s, [], mu);
    % convert centred polynomial to plain powers of SOC for the estimator
    c  = poly_uncentre(p, mu);
    C.ocv = c(:)';
    C.rmse_V = sqrt(mean((polyval(C.ocv, D.soc_ref) - ocv_meas).^2));
    C.monotonic = all(diff(polyval(C.ocv, s)) > 0);
    C.train = sprintf('%s discharge #%d', train_cell, train_idx);
    fprintf('  [calibrate] %s : OCV fit RMSE = %.1f mV, monotonic = %d, OCV(0)=%.3f OCV(1)=%.3f\n', ...
        C.train, 1e3 * C.rmse_V, C.monotonic, polyval(C.ocv, 0), polyval(C.ocv, 1));
    if v(end) < v(1)
        warning('bms_nasa_calibrate:shape', 'OCV curve is not increasing with SOC.');
    end

    % ---- write generated, codegen-friendly data file ---------------------
    here = fileparts(mfilename('fullpath'));
    fid = fopen(fullfile(here, 'bms_nasa_cal_data.m'), 'w');
    fprintf(fid, 'function C = bms_nasa_cal_data()\n');
    fprintf(fid, '%%BMS_NASA_CAL_DATA Auto-generated by BMS_NASA_CALIBRATE (%s). Do not edit by hand.\n', C.train);
    fprintf(fid, '    C.ocv = [%s];\n', strjoin(arrayfun(@(x) sprintf('%.10g', x), C.ocv, 'UniformOutput', false), ', '));
    fprintf(fid, '    C.R0 = %g; C.R1 = %g; C.R2 = %g; C.C1 = %g; C.C2 = %g; C.Qn = %g;\n', ...
        C.R0, C.R1, C.R2, C.C1, C.C2, C.Qn);
    fprintf(fid, '    C.rmse_V = %.6g;\nend\n', C.rmse_V);
    fclose(fid);
    clear bms_nasa_cal_data bms_params
end

function c = poly_uncentre(p, mu)
% p are coefficients of x_n = (x - mu(1)) / mu(2); return coefficients in x.
    n = numel(p);  c = zeros(1, n);
    base = 1;                                  % (x - m)/s as polynomial in x
    lin  = [1, -mu(1)] / mu(2);
    for i = n:-1:1                             % p(i) multiplies x_n^(n-i)
        pw = 1;
        for j = 1:(n - i),  pw = conv(pw, lin);  end
        c(end - numel(pw) + 1:end) = c(end - numel(pw) + 1:end) + p(i) * pw;
    end
    base = base; %#ok<NASGU>
end
