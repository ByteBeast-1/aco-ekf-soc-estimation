%% Advanced Automated Simulink Model Builder for ACO-EKF Battery SOC Estimation
%  ========================================================================
%  Description: MATLAB script that programmatically constructs an advanced,
%               presentation-ready Simulink Model (.slx) for Lithium-Ion Battery 
%               SOC estimation using Model-Based Design (MBD) standards.
%
%  Architecture:
%    1. Current Source (Pulse Generator simulating dynamic load)
%    2. Battery Plant Subsystem (Simulates real physics + sensor noise)
%    3. ACO-EKF Controller Subsystem (The novel algorithm brain)
%    4. Multiplexers and Real-Time Comparison Scopes
%  ========================================================================

function build_advanced_simulink_model()
    clc;
    model_name = 'advanced_bms_aco_ekf';
    fprintf('=================================================================\n');
    fprintf('  Building Advanced MBD Simulink Model: %s.slx\n', model_name);
    fprintf('=================================================================\n\n');

    % Close existing model if open
    if bdIsLoaded(model_name)
        close_system(model_name, 0);
    end

    % Create new Simulink model
    new_system(model_name);
    open_system(model_name);

    % Configure Solver (Fixed-step discrete solver at dt = 1s)
    set_param(model_name, 'SolverType', 'Fixed-step');
    set_param(model_name, 'Solver', 'FixedStepDiscrete');
    set_param(model_name, 'FixedStep', '1.0');
    set_param(model_name, 'StopTime', '3600');

    % -------------------------------------------------------------------
    % 1. Create Current Source (Dynamic Pulse Load)
    % -------------------------------------------------------------------
    add_block('simulink/Sources/Pulse Generator', [model_name '/Drive_Cycle_Current']);
    set_param([model_name '/Drive_Cycle_Current'], ...
        'Amplitude', '2.5', 'Period', '100', 'PulseWidth', '50', 'PhaseDelay', '0', ...
        'Position', [50, 200, 100, 240]);

    % -------------------------------------------------------------------
    % 2. Create Battery Plant Subsystem (The "Real World")
    % -------------------------------------------------------------------
    add_block('simulink/User-Defined Functions/MATLAB Function', [model_name '/Battery_Physics_Plant']);
    set_param([model_name '/Battery_Physics_Plant'], 'Position', [200, 100, 360, 200]);

    sf = Stateflow.Root;
    plant_block = sf.find('-isa', 'Stateflow.EMChart', 'Path', [model_name '/Battery_Physics_Plant']);
    
    plant_code = sprintf([ ...
        'function [True_SOC, Noisy_Voltage, True_Voltage] = f(I_load)\n' ...
        '%% Simulates the real battery physics (1RC Thevenin) and noisy sensors\n' ...
        'persistent soc v_core is_init;\n' ...
        'if isempty(is_init)\n' ...
        '    soc = 0.95; %% Starting at 95%% True SOC\n' ...
        '    v_core = 0.0;\n' ...
        '    is_init = 1;\n' ...
        'end\n' ...
        'R0 = 0.015; R1 = 0.010; C1 = 3000; Qn = 7200; dt = 1.0;\n' ...
        'a = exp(-dt/(R1*C1)); b = R1*(1-a);\n' ...
        '%% Update true states\n' ...
        'soc = min(max(soc - (I_load*dt)/Qn, 0.0), 1.0);\n' ...
        'v_core = a*v_core + b*I_load;\n' ...
        '%% Calculate true voltage using 8th order OCV polynomial\n' ...
        'ocv = -21.75*soc^8 + 82.26*soc^7 - 125.3*soc^6 + 99.63*soc^5 - 44.5*soc^4 + 11.34*soc^3 - 1.58*soc^2 + 1.503*soc + 3.013;\n' ...
        'True_Voltage = ocv - v_core - R0*I_load;\n' ...
        '%% Add realistic sensor noise (Gaussian)\n' ...
        'Noisy_Voltage = True_Voltage + 0.01 * randn();\n' ...
        'True_SOC = soc * 100.0;\n' ...
    ]);
    plant_block.Script = plant_code;

    % -------------------------------------------------------------------
    % 3. Create ACO-EKF Controller Subsystem (The "BMS Brain")
    % -------------------------------------------------------------------
    add_block('simulink/User-Defined Functions/MATLAB Function', [model_name '/ACO_EKF_Controller']);
    set_param([model_name '/ACO_EKF_Controller'], 'Position', [450, 200, 610, 300]);

    ctrl_block = sf.find('-isa', 'Stateflow.EMChart', 'Path', [model_name '/ACO_EKF_Controller']);
    
    ekf_code = sprintf([ ...
        'function [Est_SOC, Est_Voltage] = f(I_meas, Vt_meas)\n' ...
        '%% ACO-Tuned EKF Algorithm\n' ...
        'persistent x_hat P is_init;\n' ...
        'if isempty(is_init)\n' ...
        '    x_hat = [0.80; 0.0]; %% Initial guess with 15%% error\n' ...
        '    P = [0.01 0; 0 0.0025];\n' ...
        '    is_init = 1;\n' ...
        'end\n' ...
        'R0 = 0.015; R1 = 0.010; C1 = 3000; Qn = 7200; dt = 1.0;\n' ...
        'a = exp(-dt/(R1*C1)); b = R1*(1-a);\n' ...
        '%% ACO Optimized Matrices Q* and R*\n' ...
        'Q = [1e-7 0; 0 1e-7]; R = 2.455e-3;\n' ...
        '%% 1. Predict\n' ...
        'soc_p = min(max(x_hat(1) - (I_meas*dt)/Qn, 0.0), 1.0);\n' ...
        'vp_p  = a*x_hat(2) + b*I_meas;\n' ...
        'x_p   = [soc_p; vp_p];\n' ...
        'F     = [1 0; 0 a];\n' ...
        'P_p   = F*P*F'' + Q;\n' ...
        '%% 2. Voltage Predict\n' ...
        'ocv = -21.75*soc_p^8 + 82.26*soc_p^7 - 125.3*soc_p^6 + 99.63*soc_p^5 - 44.5*soc_p^4 + 11.34*soc_p^3 - 1.58*soc_p^2 + 1.503*soc_p + 3.013;\n' ...
        'Est_Voltage = ocv - vp_p - R0*I_meas;\n' ...
        'r = Vt_meas - Est_Voltage;\n' ...
        '%% 3. Correct (Joseph Form)\n' ...
        'docv = -174.0*soc_p^7 + 575.8*soc_p^6 - 752.0*soc_p^5 + 498.2*soc_p^4 - 178.0*soc_p^3 + 34.02*soc_p^2 - 3.165*soc_p + 1.503;\n' ...
        'H = [docv, -1.0];\n' ...
        'S = H*P_p*H'' + R;\n' ...
        'K = (P_p*H'')/S;\n' ...
        'x_upd = x_p + K*r;\n' ...
        'x_upd(1) = min(max(x_upd(1), 0.0), 1.0);\n' ...
        'IKH = eye(2) - K*H;\n' ...
        'P_upd = IKH*P_p*IKH'' + K*R*K'';\n' ...
        'x_hat = x_upd; P = P_upd;\n' ...
        'Est_SOC = x_hat(1)*100.0;\n' ...
    ]);
    ctrl_block.Script = ekf_code;

    % -------------------------------------------------------------------
    % 4. Create Multiplexers and Scopes
    % -------------------------------------------------------------------
    % Mux for SOC Comparison
    add_block('simulink/Signal Routing/Mux', [model_name '/Mux_SOC']);
    set_param([model_name '/Mux_SOC'], 'Inputs', '2', 'Position', [700, 100, 705, 140]);
    
    % SOC Scope
    add_block('simulink/Sinks/Scope', [model_name '/SOC_Comparison_Scope']);
    set_param([model_name '/SOC_Comparison_Scope'], 'Position', [750, 105, 780, 135]);
    
    % Mux for Voltage Comparison
    add_block('simulink/Signal Routing/Mux', [model_name '/Mux_Voltage']);
    set_param([model_name '/Mux_Voltage'], 'Inputs', '3', 'Position', [700, 180, 705, 240]);
    
    % Voltage Scope
    add_block('simulink/Sinks/Scope', [model_name '/Voltage_Scope']);
    set_param([model_name '/Voltage_Scope'], 'Position', [750, 195, 780, 225]);
    
    % Subtract block for SOC Error
    add_block('simulink/Math Operations/Subtract', [model_name '/Subtract_Error']);
    set_param([model_name '/Subtract_Error'], 'Inputs', '+-', 'Position', [700, 270, 730, 300]);
    
    % Error Scope
    add_block('simulink/Sinks/Scope', [model_name '/SOC_Error_Scope']);
    set_param([model_name '/SOC_Error_Scope'], 'Position', [780, 270, 810, 300]);

    % -------------------------------------------------------------------
    % 5. Connect Blocks with Signal Lines
    % -------------------------------------------------------------------
    % Current source to Plant
    add_line(model_name, 'Drive_Cycle_Current/1', 'Battery_Physics_Plant/1', 'autorouting', 'on');
    
    % Current source to Controller
    add_line(model_name, 'Drive_Cycle_Current/1', 'ACO_EKF_Controller/1', 'autorouting', 'on');
    
    % Plant Noisy Voltage to Controller Noisy Voltage Input
    add_line(model_name, 'Battery_Physics_Plant/2', 'ACO_EKF_Controller/2', 'autorouting', 'on');
    
    % Connections to SOC Mux
    add_line(model_name, 'Battery_Physics_Plant/1', 'Mux_SOC/1', 'autorouting', 'on'); % True SOC
    add_line(model_name, 'ACO_EKF_Controller/1', 'Mux_SOC/2', 'autorouting', 'on');    % Est SOC
    add_line(model_name, 'Mux_SOC/1', 'SOC_Comparison_Scope/1', 'autorouting', 'on');
    
    % Connections to Voltage Mux
    add_line(model_name, 'Battery_Physics_Plant/3', 'Mux_Voltage/1', 'autorouting', 'on'); % True V
    add_line(model_name, 'Battery_Physics_Plant/2', 'Mux_Voltage/2', 'autorouting', 'on'); % Noisy V
    add_line(model_name, 'ACO_EKF_Controller/2', 'Mux_Voltage/3', 'autorouting', 'on');    % Est V
    add_line(model_name, 'Mux_Voltage/1', 'Voltage_Scope/1', 'autorouting', 'on');
    
    % Connections to Error Subtractor (Est SOC - True SOC)
    add_line(model_name, 'ACO_EKF_Controller/1', 'Subtract_Error/1', 'autorouting', 'on');
    add_line(model_name, 'Battery_Physics_Plant/1', 'Subtract_Error/2', 'autorouting', 'on');
    add_line(model_name, 'Subtract_Error/1', 'SOC_Error_Scope/1', 'autorouting', 'on');

    % Save model
    save_system(model_name);
    fprintf('  [Simulink Builder] Advanced MBD architecture successfully generated!\n');
    fprintf('  Model saved as: %s.slx\n', model_name);
    fprintf('=================================================================\n');
end
